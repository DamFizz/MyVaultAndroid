/**
 * Writes core/src/test/resources/fixtures/analysis.json: outputs of the web app's own strength
 * estimator, security analysis, generator entropy and SHA-1 (breach check) for the Kotlin ports to match.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { estimateStrength } from '@web/lib/strength';
import { analyzeVault } from '@web/lib/security-analysis';
import { generatedPasswordEntropy, passphraseEntropy, passwordPoolSize, DEFAULT_PASSWORD_OPTIONS, DEFAULT_PASSPHRASE_OPTIONS, PASSPHRASE_WORDLIST } from '@web/lib/generator';
import { sha1Hex } from '@web/lib/hibp';
import { emptyItem, type VaultItem } from '@web/vault/types';

const PASSWORDS = [
  '', 'a', 'password', 'P@ssw0rd', 'Password123!', 'qwerty', 'qwertyuiop12', 'iloveyou2024', 'abc123', 'abcdefgh',
  '12345678901234567890', 'aaaaaaaaaaaa', 'Summer2019!', 'correct horse battery staple', 'Tr0ub4dor&3', 'zxcvbnm,./',
  'kL9#mQ2$vX7!pR4z', 'h7Gk2Lm9Qz', 'sayangku123', 'MALAYSIA2026', 'x', 'Xy7!', 'aB3$eF6&hJ9*', 'timber-glide-orbit-lemon',
  'Kata-Laluan-Café-42!', 'пароль-секрет-99', '1qaz2wsx3edc', 'admin123', 'welcome1', 'N0t-A-Comm0n-0ne-At-All-2',
  'the quick brown fox', 'zzzzzzzz1', '9876543210', 'Fortnite2020', 'r4nd0m$tring', 'LongerButOnlyLowercaseLetters',
];

test('generate analysis vectors', async () => {
  const now = 1_800_000_000_000;
  const day = 86_400_000;
  const mk = (id: string, patch: Partial<VaultItem>): VaultItem => ({ ...emptyItem('login', id, now - 10 * day), title: id, ...patch });
  const items: VaultItem[] = [
    mk('a', { title: 'Site A', url: 'https://www.site-a.com/login', username: 'Dam', password: 'password', categoryId: 'c1' }),
    mk('b', { title: 'Site A dup', url: 'site-a.com', username: 'dam', password: 'kL9#mQ2$vX7!pR4z', passwordChangedAt: now - 400 * day }),
    mk('c', { title: 'Reuse 1', email: 'someone@example.com', password: 'kL9#mQ2$vX7!pR4z' }),
    mk('d', { title: 'No login', url: 'https://d.example', password: 'aB3$eF6&hJ9*xY2@', sectionId: 's1' }),
    mk('e', { title: 'No password', username: 'x' }),
    mk('f', { title: 'Archived', password: 'password', archivedAt: now }),
    mk('g', { title: 'Trashed', password: 'password', trashedAt: now }),
    { ...emptyItem('note', 'n', now), title: 'A note' },
    mk('h', { title: 'Old one', username: 'old', url: 'old.example', password: 'N0t-A-Comm0n-0ne-At-All-2', createdAt: now - 800 * day }),
  ];
  const short = { ...DEFAULT_PASSWORD_OPTIONS, length: 12, symbols: false, excludeAmbiguous: false };
  const out = {
    comment: 'Generated by tools/webfixture/gen-analysis.fixture.ts from the web app modules. Do not edit.',
    strength: await Promise.all(PASSWORDS.map(async (pw) => ({ pw, ...estimateStrength(pw), sha1: await sha1Hex(pw) }))),
    security: { now, oldPasswordDays: 365, items, report: analyzeVault(items, { oldPasswordDays: 365, now }) },
    generator: {
      defaultPool: passwordPoolSize(DEFAULT_PASSWORD_OPTIONS),
      defaultEntropy: generatedPasswordEntropy(DEFAULT_PASSWORD_OPTIONS),
      shortPool: passwordPoolSize(short),
      shortEntropy: generatedPasswordEntropy(short),
      passphraseEntropy: passphraseEntropy(DEFAULT_PASSPHRASE_OPTIONS),
      words: PASSPHRASE_WORDLIST.length,
      firstWord: PASSPHRASE_WORDLIST[0],
      lastWord: PASSPHRASE_WORDLIST[PASSPHRASE_WORDLIST.length - 1],
    },
  };
  writeFileSync(path.resolve(import.meta.dirname, '../../core/src/test/resources/fixtures/analysis.json'), JSON.stringify(out, null, 2) + '\n');
});
